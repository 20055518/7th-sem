import { useEffect, useState } from "react";
import { Link } from "react-router-dom";

import AppNav from "../components/AppNav";
import { getMyQueue } from "../api";

import "./PatientQR.css";


export default function PatientQR() {
  const [queue, setQueue] =
    useState(null);

  const [error, setError] =
    useState("");

  const [loading, setLoading] =
    useState(true);


  // ==========================================================
  // LOAD PATIENT QUEUE
  // ==========================================================

  useEffect(() => {
    getMyQueue()
      .then((data) => {
        setQueue(data);
      })
      .catch((error) => {
        const message = String(error?.message || "");
        if (
          error?.status === 404 ||
          message.toLowerCase().includes("no queue entry found")
        ) {
          setQueue(null);
          setError("");
          return;
        }

        setError(
          error?.message ||
            "Unable to load your queue.",
        );
      })
      .finally(() => {
        setLoading(false);
      });
  }, []);


  return (
    <main className="patient-qr-page">

      <AppNav />


      {/* ======================================================
          PAGE HEADER
          ====================================================== */}

      <section className="page-header">

        <div>

          <p className="eyebrow">
            QR ACCESS
          </p>

          <h1>
            My Queue QR
          </h1>

          <p className="muted">
            Use the official QR code provided
            by the reception desk to access
            your live queue.
          </p>

        </div>

      </section>


      {/* ======================================================
          ERROR
          ====================================================== */}

      {error && (
        <div className="alert danger">
          {error}
        </div>
      )}


      {/* ======================================================
          LOADING
          ====================================================== */}

      {loading && (
        <div className="loading-card">
          Loading your queue...
        </div>
      )}


      {/* ======================================================
          QUEUE EXISTS
          ====================================================== */}

      {!loading && queue && (
        <section className="patient-qr-card">

          <div className="patient-qr-header">

            <div>

              <p className="eyebrow">
                YOUR TOKEN
              </p>

              <h2>
                #
                {String(
                  queue.token_number,
                ).padStart(
                  3,
                  "0",
                )}
              </h2>

            </div>


            <span className="live-pill">
              ● Active
            </span>

          </div>


          {/* ==================================================
              QR INFORMATION
              ================================================== */}

          <div className="patient-qr-info">

            <div className="qr-icon-box">
              QR
            </div>

            <div>

              <h3>
                Official Queue QR
              </h3>

              <p className="muted">
                Your queue QR is generated by
                the reception/admin account and
                provided to you after registration.
              </p>

            </div>

          </div>


          {/* ==================================================
              QUEUE DETAILS
              ================================================== */}

          <div className="patient-qr-details">

            <div className="patient-qr-detail">

              <span>
                Department
              </span>

              <strong>
                {queue.department ||
                  "General"}
              </strong>

            </div>


            <div className="patient-qr-detail">

              <span>
                Status
              </span>

              <strong>
                {String(
                  queue.status || "",
                )
                  .replaceAll(
                    "_",
                    " ",
                  )
                  .replace(
                    /\b\w/g,
                    (char) =>
                      char.toUpperCase(),
                  )}
              </strong>

            </div>


            <div className="patient-qr-detail">

              <span>
                Position
              </span>

              <strong>
                {queue.position ??
                  "—"}
              </strong>

            </div>

          </div>


          {/* ==================================================
              INSTRUCTION
              ================================================== */}

          <div className="patient-qr-instruction">

            <p className="eyebrow">
              HOW TO USE
            </p>

            <ol>

              <li>
                Receive the official queue QR
                from the reception desk.
              </li>

              <li>
                Scan the QR using your phone
                camera.
              </li>

              <li>
                Your identity is verified against
                your logged-in patient account.
              </li>

              <li>
                After verification, you can see
                your own queue information.
              </li>

            </ol>

          </div>


          {/* ==================================================
              ACTIONS
              ================================================== */}

          <div className="patient-qr-actions">

            <Link
              className="button primary"
              to="/queue-access"
            >
              Scan Queue QR
            </Link>

            <Link
              className="button secondary"
              to="/patient-dashboard"
            >
              Back to My Queue
            </Link>

          </div>

        </section>
      )}


      {/* ======================================================
          NO QUEUE
          ====================================================== */}

      {!loading &&
        !queue &&
        !error && (
          <section className="empty-card patient-qr-empty">

            <p className="eyebrow">
              QUEUE
            </p>

            <h2>
              No Active Queue
            </h2>

            <p className="muted">
              You do not currently have an
              active queue entry.
            </p>

            <Link
              className="button primary"
              to="/join-queue"
            >
              Join Queue
            </Link>

          </section>
        )}

    </main>
  );
}